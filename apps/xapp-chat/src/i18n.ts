export function useT() {
  const { s } = useApp();
  const i = s.lang === 'en' ? 0 : s.lang === 'fr' ? 1 : 2;
  return {
    lang: s.lang,
    rtl: s.lang === 'ar',
    t: (k: Key, v?: Record<string, string | number>) => {
      let x: string = S[k][i];
      if (v) for (const [a, b] of Object.entries(v)) x = x.split(`{{${a}}}`).join(String(b));
      return x;
    },
    p: (l: L3) => l[i],
  };
}
