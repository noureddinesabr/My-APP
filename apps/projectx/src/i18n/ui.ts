export type UiKey = keyof typeof S;
const IDX: Record<UiLang, number> = { en: 0, fr: 1, ar: 2 };
export function tr(lang: UiLang, key: UiKey, vars: Record<string, string | number> = {}) {
  let s: string = S[key][IDX[lang]];
  // "one|many" forms, chosen by {n}
  if (s.includes('|') && 'n' in vars) s = s.split('|')[Number(vars.n) === 1 ? 0 : 1];
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
export const browserUiLang = (): UiLang => {
  const l = (typeof navigator !== 'undefined' ? navigator.language : 'en').toLowerCase();
  return l.startsWith('ar') ? 'ar' : l.startsWith('fr') ? 'fr' : 'en';
};
