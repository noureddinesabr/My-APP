/** The language, its words and its direction, for any screen. */
export function useT() {
  const { lang } = useStore();
  const rtl = lang === 'ar';
  return {
    lang,
    rtl,
    t: (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars),
    /** "A → B" that reads the right way in Arabic. */
    route: (a: string, b: string) => (rtl ? `${a} ← ${b}` : `${a} → ${b}`),
  };
}

/** Called once at start-up: the page direction for the browser preview. */
export function applyDirection(lang: Lang) {
  if (Platform.OS === 'web' && typeof document !== 'undefined') document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

/** Changes the language; on phones a switch to or from Arabic restarts the app once to flip the layout. */
export async function setLanguage(lang: Lang) {
  update((s) => ({ ...s, lang }));
  applyDirection(lang);
  const rtl = lang === 'ar';
  if (Platform.OS !== 'web' && I18nManager.isRTL !== rtl) {
    I18nManager.allowRTL(rtl);
    I18nManager.forceRTL(rtl);
    // Give the store a moment to save, then restart so the whole layout flips.
    await new Promise((r) => setTimeout(r, 400));
    const { reloadAppAsync } = await import('expo');
    await reloadAppAsync().catch(() => {});
  }
}
