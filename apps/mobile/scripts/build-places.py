"""
Builds src/constants/places-data.ts, the offline place list behind the pickup / drop-off search:
- every Moroccan town in GeoNames (cities500.json from the `geonamescache` package, CC BY 4.0),
  with its Arabic name where GeoNames has one;
- the hand-written neighbourhoods, streets and landmarks in scripts/data/places-ma.txt.

Run: python3 scripts/build-places.py <path to geonamescache/data/cities500.json>
"""
import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
ARABIC = re.compile(r'[؀-ۿ]')

# The main cities (ids must match src/constants/cities.ts).
cities_ts = open(os.path.join(ROOT, 'src/constants/cities.ts'), encoding='utf-8').read()
CITIES = [
    (m.group(1), float(m.group(2)), float(m.group(3)))
    for m in re.finditer(r"id: '([a-z]+)'.*?lat: ([\d.-]+), lng: ([\d.-]+)", cities_ts)
]
CITY_IDS = {c[0] for c in CITIES}


def km(a_lat, a_lng, b_lat, b_lng):
    dlat = math.radians(b_lat - a_lat)
    dlng = math.radians(b_lng - a_lng)
    h = math.sin(dlat / 2) ** 2 + math.cos(math.radians(a_lat)) * math.cos(math.radians(b_lat)) * math.sin(dlng / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(h))


def nearest_city(lat, lng):
    return min(CITIES, key=lambda c: km(lat, lng, c[1], c[2]))


def q(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'") + "'"


rows = []
seen = set()

# Curated places first (they win on duplicates).
for line in open(os.path.join(HERE, 'data/places-ma.txt'), encoding='utf-8'):
    line = line.strip()
    if not line or line.startswith('#'):
        continue
    parts = line.split('|')
    kind, city, fr, ar, lat, lng = parts[:6]
    en = parts[6] if len(parts) > 6 else fr
    assert city in CITY_IDS, f'unknown city {city}'
    slug = re.sub(r'[^a-z0-9]+', '-', fr.lower().encode('ascii', 'ignore').decode()).strip('-')
    pid = f'{city}-{slug}'
    if pid in seen:
        continue
    seen.add(pid)
    rows.append((pid, city, kind, ar, fr, en, float(lat), float(lng), 0))

def key(text):
    import unicodedata
    plain = unicodedata.normalize('NFD', text.lower()).encode('ascii', 'ignore').decode()
    return re.sub(r'[^a-z]', '', plain)


curated = [(key(r[4]), r[6], r[7]) for r in rows]

# GeoNames towns (not the main cities themselves, nor places already in the curated list).
towns = json.load(open(sys.argv[1], encoding='utf-8'))
for town in sorted(towns.values(), key=lambda t: -t['population']):
    if town['countrycode'] != 'MA':
        continue
    lat, lng = town['latitude'], town['longitude']
    city = nearest_city(lat, lng)
    if km(lat, lng, city[1], city[2]) < 4:
        continue  # the city itself, or a duplicate of it
    if any(name == key(town['name']) and km(lat, lng, c_lat, c_lng) < 8 for name, c_lat, c_lng in curated):
        continue
    arabic = next((name for name in town['alternatenames'] if ARABIC.search(name)), None)
    fr = town['name']
    pid = 'town-' + str(town['geonameid'])
    rows.append((pid, city[0], 'town', arabic or fr, fr, fr, round(lat, 4), round(lng, 4), town['population']))

out = [
    '// Generated by scripts/build-places.py — do not edit by hand.',
    '// Towns: GeoNames (CC BY 4.0). Neighbourhoods, streets and landmarks: scripts/data/places-ma.txt (approximate centres).',
    '',
    "import type { CityId } from '@/constants/cities';",
    "import type { PlaceKind } from '@/lib/place-search';",
    '',
    'export type PlaceRow = [id: string, cityId: CityId, kind: PlaceKind, ar: string, fr: string, en: string, lat: number, lng: number, population: number];',
    '',
    'export const PLACE_ROWS: PlaceRow[] = [',
]
for pid, city, kind, ar, fr, en, lat, lng, pop in rows:
    out.append(f'  [{q(pid)}, {q(city)}, {q(kind)}, {q(ar)}, {q(fr)}, {q(en)}, {lat}, {lng}, {pop}],')
out.append('];')
open(os.path.join(ROOT, 'src/constants/places-data.ts'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(rows), 'places', sum(1 for r in rows if r[2] == 'town'), 'towns')
